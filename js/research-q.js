// ── Проверка «нет контактов и ФИО» — те же выражения, что в sql/014 research_pii_ok ──
const PII = [
  [/[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}/i, 'адрес почты'],
  [/(\+7|(^|[^0-9])8)[ ()-]*[0-9]{3}[ ()-]*[0-9]{3}[ -]*[0-9]{2}[ -]*[0-9]{2}/, 'номер телефона'],
  [/\+[0-9][0-9 ()-]{9,}/, 'номер телефона'],
  [/(^|[^a-z0-9_.])@[a-z][a-z0-9_]{4,}/i, 'логин мессенджера'],
];
/** Список проблем: [{path, what}]. Пусто — можно сохранять. */
export function piiProblems(data) {
  const out = [];
  const walk = (v, path) => {
    if (typeof v === 'string') { for (const [re, what] of PII) if (re.test(v)) { out.push({ path, what }); break; } }
    else if (v && typeof v === 'object') for (const [k, x] of Object.entries(v)) walk(x, path ? `${path}.${k}` : k);
  };
  walk(data, '');
  const name = ((data.respondent || {}).name || '').trim();
  if (name && name.split(/\s+/).length > 1) out.push({ path: 'respondent.name', what: 'нужно одно слово — только имя, без фамилии и отчества' });
  return out;
}

// ── CSV: разделитель «;», UTF-8 с BOM — открывается в Excel с русскими буквами ──
const lab = (opts, v) => { const o = opts.find(x => x[0] === v); return o ? o[1] : (v == null ? '' : String(v)); };
const bool = v => (v === true ? 'да' : v === false ? 'нет' : '');
function cell(v) {
  if (v == null) return '';
  let s = String(v);
  // Защита от формул в Excel: ячейка не должна начинаться с = + - @ (кроме чисел).
  if (/^[=+\-@\t\r]/.test(s) && !/^-?\d+([.,]\d+)?$/.test(s)) s = "'" + s;
  return /[;"\n\r]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
}

/** rows: [{...interview row, codes: {И1: 'episode', ...}}] → текст CSV с BOM. */
export function toCsv(rows) {
  const maxPets = Math.max(1, ...rows.map(r => ((r.data || {}).pets || []).length));
  const head = ['code', 'held_on', 'interviewer', 'segment', 'channel', 'format', 'consent_record', 'has_contact', 'status', 'created_at', 'updated_at'];
  RESPONDENT.forEach(f => head.push('resp_' + f.k));
  for (let i = 1; i <= maxPets; i++) PET.forEach(f => head.push(`pet${i}_${f.k}`));
  MONEY.forEach(f => head.push('money_' + f.k));
  head.push('money_spend_year_for_avg');
  BLOCKS.forEach(b => head.push(b.k + '_told', b.k + '_quote'));
  head.push('discrepancies');
  COMMITMENTS.forEach(c => head.push('commit_' + c[0]));
  head.push('commit_text');
  HYPOTHESES.forEach(h => head.push(h[0]));

  const val = (f, v) => (f.type === 'select' ? lab(f.opts, v) : v);
  const lines = [head.map(cell).join(';')];
  for (const r of rows) {
    const d = r.data || {}, resp = d.respondent || {}, pets = d.pets || [], m = d.money || {}, bl = d.blocks || {}, cm = d.commitments || {}, codes = r.codes || {};
    const line = [r.code, r.held_on, r.interviewer, r.segment, r.channel, lab(FORMATS, r.format), bool(r.consent_record), bool(r.has_contact), lab(STATUSES, r.status), r.created_at, r.updated_at];
    RESPONDENT.forEach(f => line.push(val(f, resp[f.k])));
    for (let i = 0; i < maxPets; i++) PET.forEach(f => line.push(val(f, (pets[i] || {})[f.k])));
    MONEY.forEach(f => line.push(val(f, m[f.k])));
    // Сумма «не знает» в средние не включается: отдельная колонка для расчётов.
    line.push(m.spend_year_basis === 'unknown' ? '' : m.spend_year);
    BLOCKS.forEach(b => line.push((bl[b.k] || {}).told, (bl[b.k] || {}).quote));
    line.push(d.discrepancies);
    COMMITMENTS.forEach(c => line.push(bool(!!cm[c[0]])));
    line.push(cm.text);
    HYPOTHESES.forEach(h => line.push(lab(VERDICTS, codes[h[0]] || 'not_asked')));
    lines.push(line.map(cell).join(';'));
  }
  return '﻿' + lines.join('\r\n') + '\r\n';
}

