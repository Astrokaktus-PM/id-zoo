const ORDER = 'ABCDE';
const worse = (a, b) => (ORDER.indexOf(a) >= ORDER.indexOf(b) ? a : b);
const REASON = {
  water: { sometimes: 'вода иногда заканчивается', often: 'воды часто нет несколько часов', halfday: 'воды не было полдня и дольше' },
  table: { few: 'еда со стола 2–4 раза в неделю', daily: 'еда со стола почти каждый день', constant: 'ест со стола постоянно' },
  place: { disturbed: 'в своём месте беспокоят', no: 'нет места, где не трогают' },
  pain: { sometimes: 'иногда прихрамывает', clear: 'боль явно мешает', strong: 'боль сильно мешает' },
  fear: { rare: 'страх, редко', daily: 'страх почти каждый день', blocks: 'страх мешает выходить' },
};

/** Степени ограничителей из ответов. Неотвеченный вопрос не влияет; ограничитель без
 *  единого ответа не пишется вовсе (остаётся прежняя степень). */
export function gradesFrom(answers) {
  const out = {};
  for (const q of QUESTIONS) {
    if (!q.gate || !answers[q.id]) continue;
    const o = q.opts.find(x => x[0] === answers[q.id]); if (!o) continue;
    const g = o[2], why = REASON[q.id] && REASON[q.id][answers[q.id]];
    const cur = out[q.gate];
    if (!cur) out[q.gate] = { gate: q.gate, grade: g, reasons: why ? [why] : [] };
    else { cur.grade = worse(cur.grade, g); if (why) cur.reasons.push(why); }
  }
  return Object.values(out).map(x => ({ gate: x.gate, grade: x.grade, reason: x.reasons.join('; ').slice(0, 200) || null }));
}

/** Тексты к ответам: не число, а что делать. */
export function adviceFrom(answers) {
  const a = [];
  if (['clear', 'strong'].includes(answers.pain)) a.push('Покажите врачу: пока болит, прогулки и игры доходят только частью.');
  if (answers.table === 'constant') a.push('Еда со стола несколько раз в день — риск для веса. Проверьте вес в разделе «Питание» и обсудите с врачом.');
  if (['often', 'halfday'].includes(answers.water)) a.push('Вода — базовое условие: вторая миска или поилка решают это дешевле всего.');
  if (answers.fear === 'blocks') a.push('Если страх мешает выходить, это повод для специалиста по поведению, а не для лишних прогулок.');
  return a;
}

