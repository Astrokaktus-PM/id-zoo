/** Пора ли переспросить: последняя строка анкеты (ответ или «потом») старше 14 дней, или анкеты нет. */
export function surveyDue(list, T) {
  if (!list.length) return { due: true, never: true };
  const last = list[0];
  const days = Math.round((new Date(T + 'T12:00:00') - new Date(last.answered_on + 'T12:00:00')) / 86400000);
  const lastAnswered = list.find(x => !x.skipped) || null;
  return { due: days >= 14, never: !lastAnswered, last, lastAnswered };
}
